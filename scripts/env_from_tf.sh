#!/usr/bin/env bash
# Write .env (git-ignored) for docker compose from terraform/main outputs, so
# container settings always match what Terraform created.
#
# No credentials go in .env: containers get them from the EC2 instance role
# via IMDS (hop limit 2).
#
# Usage: scripts/env_from_tf.sh
set -euo pipefail

cd "$(dirname "$0")/.."

tf() { terraform -chdir=terraform/main output -raw "$1"; }

# Write to a temp file and rename, so a failure never leaves a partial .env.
tmp="$(mktemp .env.XXXXXX)"
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by scripts/env_from_tf.sh from terraform output. Do not commit."
  echo "AWS_REGION=${AWS_REGION:-ap-south-1}"
  echo "AWS_DEFAULT_REGION=${AWS_REGION:-ap-south-1}"
  echo "REELOPS_MEDIA_BUCKET=$(tf media_bucket_name)"
  echo "REELOPS_JOBS_TABLE=$(tf jobs_table_name)"
  echo "REELOPS_JOBS_QUEUE_URL=$(tf jobs_queue_url)"
} >"$tmp"
chmod 600 "$tmp"
mv "$tmp" .env
trap - EXIT

# .env contains the account ID (in the queue URL and bucket name).
if ! git check-ignore -q .env; then
  echo "WARNING: .env is NOT git-ignored; do not commit it" >&2
fi
echo "Wrote .env ($(grep -c '^[A-Z]' .env) variables)"
